//! THIRD_PARTY_NOTICES.md must cover what ships in dock.exe and in tasks.exe (the apps that carry crates of their own).
//! Regenerate the crate part with `pwsh tools/gen-notices.ps1`.

use std::os::windows::process::CommandExt;
use std::process::Command;

/// `CREATE_NO_WINDOW` (winbase.h): every process a test starts carries it (lint `every_spawned_process_has_no_window`).
const CREATE_NO_WINDOW: u32 = 0x0800_0000;

fn read(rel: &str) -> Vec<u8> {
    let p = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(rel);
    std::fs::read(&p).unwrap_or_else(|e| panic!("read {}: {e}", p.display()))
}

/// A line of `cargo tree` that names a path package (`name vX.Y.Z (<path>)`): returns the package name.
fn local_package(line: &str) -> Option<&str> {
    let (name, rest) = line.split_once(" v")?;
    let (_, after) = rest.split_once(' ')?;
    (after.starts_with('(') && after != "(*)" && after != "(proc-macro)").then_some(name)
}

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    !needle.is_empty() && hay.windows(needle.len()).any(|w| w == needle)
}

#[test]
fn path_packages_are_the_suites_own() {
    assert_eq!(local_package("oled-sys v0.0.0 (C:\\x\\crates\\oled-sys)"), Some("oled-sys"));
    assert_eq!(local_package("serde v1.0.229"), None);
    assert_eq!(local_package("serde v1.0.229 (*)"), None);
}

/// The apps whose executables ship crates of their own, besides the dock (the root package).
const APPS: [&str; 1] = ["tasks"];

#[test]
fn notices_list_every_crate_in_the_exe() {
    notices_list_every_crate(&[]);
    for app in APPS {
        notices_list_every_crate(&["-p", app]);
    }
}

/// `cargo tree` of one package (the root package for no arguments) with its default features: the build that ships.
fn notices_list_every_crate(package: &[&str]) {
    let out = Command::new(env!("CARGO"))
        .creation_flags(CREATE_NO_WINDOW)
        .current_dir(env!("CARGO_MANIFEST_DIR"))
        .args([
            "tree",
            "--locked",
            "--offline",
            "-e",
            "normal",
            "--target",
            "x86_64-pc-windows-msvc",
            "--prefix",
            "none",
            "-f",
            "{p}",
        ])
        .args(package)
        .output()
        .expect("run cargo tree");
    assert!(out.status.success(), "cargo tree failed: {}", String::from_utf8_lossy(&out.stderr));
    let notices = String::from_utf8(read("THIRD_PARTY_NOTICES.md")).expect("notices are UTF-8");
    let used: Vec<&str> = notices.lines().filter_map(|l| l.strip_prefix("Used by: ")).collect();
    let text = String::from_utf8_lossy(&out.stdout);
    let mut seen = 0;
    let mut missing = Vec::new();
    for (i, line) in text.lines().enumerate() {
        if i == 0 {
            continue; // the root package, dock itself
        }
        let line = line.trim_end_matches(" (*)").trim_end_matches(" (proc-macro)");
        if let Some(name) = local_package(line) {
            // The suite's own crates are covered by the repository's LICENSE; any other path package is unlicensed code.
            if !name.starts_with("oled-") && !APPS.contains(&name) && !missing.contains(&name.to_string()) {
                missing.push(name.to_string());
            }
            continue;
        }
        let Some((name, ver)) = line.split_once(" v") else {
            continue;
        };
        seen += 1;
        let want = format!("{name} {ver}");
        let found = used.iter().any(|l| l.split(", ").any(|item| item == want));
        if !found && !missing.contains(&want) {
            missing.push(want);
        }
    }
    assert!(seen > 0, "cargo tree listed no dependency");
    assert!(missing.is_empty(), "THIRD_PARTY_NOTICES.md lacks {missing:?}: run pwsh tools/gen-notices.ps1");
}

/// Every licence text stored in tools/notices must appear byte for byte in the hand-written part of the
/// notices (above the generated-part marker), so a text that only matches a crate's licence below does not count.
#[test]
fn stored_licences_are_verbatim() {
    let notices = read("THIRD_PARTY_NOTICES.md");
    let marker: &[u8] = b"<!-- below: generated by tools/gen-notices.ps1 -->";
    let at = notices.windows(marker.len()).position(|w| w == marker).expect("THIRD_PARTY_NOTICES.md lacks the marker");
    let hand_written = &notices[..at];
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tools/notices");
    let mut names = Vec::new();
    for entry in std::fs::read_dir(&dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display())) {
        let name = entry.expect("tools/notices entry").file_name().into_string().expect("UTF-8 file name");
        let lic = read(&format!("tools/notices/{name}"));
        assert!(
            contains(hand_written, &lic),
            "THIRD_PARTY_NOTICES.md (above the marker) does not contain tools/notices/{name} verbatim"
        );
        names.push(name);
    }
    for want in ["EarTrumpet", "rust", "hashbrown", "rustc-demangle", "backtrace", "cfg-if"] {
        let want = format!("{want}-LICENSE.txt");
        assert!(names.contains(&want), "tools/notices/{want} is missing");
    }
    let s = String::from_utf8(read("tools/notices/EarTrumpet-LICENSE.txt")).expect("licence is UTF-8");
    for who in ["Yellow Elephant Productions", "Tidal Media Inc.", "Articent Group LLC"] {
        assert!(s.contains(who), "licence file does not name {who}");
    }
}

/// The crates whose package carries no licence file (AccessKit): the text kept in tools/notices-crates must be in the
/// generated part, next to the crates it covers.
#[test]
fn crates_without_a_licence_file_carry_the_stored_text() {
    let notices = String::from_utf8(read("THIRD_PARTY_NOTICES.md")).expect("notices are UTF-8");
    let lic = String::from_utf8(read("tools/notices-crates/accesskit-LICENSE-MIT.txt")).expect("licence is UTF-8");
    let at = notices.find("Used by: accesskit ").expect("notices do not name accesskit");
    let mut parts = notices[at..].split("```");
    let (users, text) = (parts.next().unwrap_or(""), parts.next().unwrap_or(""));
    assert!(text.contains(lic.trim_end()), "the AccessKit licence text is not beside its crates");
    for name in ["accesskit_consumer", "accesskit_windows"] {
        assert!(users.lines().next().is_some_and(|l| l.contains(name)), "{name} is not in the AccessKit group");
    }
}

