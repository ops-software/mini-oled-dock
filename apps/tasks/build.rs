//! Embeds tasks.exe's manifest and resources and generates its string tables. Always asInvoker: Tasks is an ordinary
//! unelevated window (no DOCK_NO_MANIFEST switch), per-monitor v2 DPI and the segment heap. The version resource names
//! the exe the way Windows' own Task Manager shows it; the icon is id 1 (tools/make-icon.ps1 -Variant tasks). Rarely
//! used system DLLs are delay-loaded. With the preview feature, the scenes under scenes/ are embedded for --preview.
//! API checked against the embed-manifest 1.5.1 and winresource 0.1 sources (`new_manifest`, `heap_type`,
//! `WindowsResource::set_icon`, `compile_for`).

use std::path::{Path, PathBuf};

use embed_manifest::manifest::{DpiAwareness, ExecutionLevel, HeapType};
use embed_manifest::{embed_manifest, new_manifest};

/// DLLs loaded on first use only (--selftest, --version and a forwarded start never map them).
const DELAY_LOAD: &[&str] =
    &["shell32.dll", "ole32.dll", "oleaut32.dll", "propsys.dll", "shlwapi.dll", "version.dll", "powrprof.dll"];

fn main() {
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    // The keyed string tables (strings/en.toml, strings/it.toml): a bad strings file fails the build.
    if let Err(e) = oled_i18n_build::generate(Path::new("strings"), &out.join("strings.rs")) {
        panic!("strings/: {e}")
    }
    write_scenes(&out.join("scenes.rs"));
    if std::env::var_os("CARGO_CFG_WINDOWS").is_some() {
        let manifest = new_manifest("MiniOledDock.Tasks")
            .requested_execution_level(ExecutionLevel::AsInvoker)
            .dpi_awareness(DpiAwareness::PerMonitorV2)
            .heap_type(HeapType::SegmentHeap);
        if let Err(e) = embed_manifest(manifest) {
            // A missing manifest must not fail the build, but it must be reported.
            println!("cargo:warning=cannot embed the manifest: {e}");
        }
        // Version resource and the application icon (id 1). FileDescription is the name Windows' own Task Manager shows;
        // it is not a UI string of the suite. No manifest here: embed-manifest owns it.
        let mut res = winresource::WindowsResource::new();
        res.set_icon("assets/tasks.ico");
        res.set("ProductName", "mini-oled-dock")
            .set("FileDescription", "Tasks")
            .set("LegalCopyright", "MIT")
            .set("OriginalFilename", "tasks.exe")
            .set("InternalName", "tasks");
        // For the tasks binary only: the examples and the test executables carry no resource.
        if let Err(e) = res.compile_for("tasks") {
            println!("cargo:warning=cannot embed the version resource: {e}");
        }
        if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
            for dll in DELAY_LOAD {
                println!("cargo:rustc-link-arg-bin=tasks=/DELAYLOAD:{dll}");
            }
            println!("cargo:rustc-link-arg-bin=tasks=delayimp.lib");
            // LOAD_LIBRARY_SEARCH_SYSTEM32 for the delay-loaded DLLs as well.
            println!("cargo:rustc-link-arg-bin=tasks=/DEPENDENTLOADFLAG:0x800");
        }
    }
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-changed=assets");
    println!("cargo:rerun-if-changed=scenes");
}

/// OUT_DIR/scenes.rs: `pub const SCENES: &[(&str, &str)]`, one (name, include_str!) per scenes/*.json sorted by name
/// with the preview feature, an empty slice without it.
fn write_scenes(file: &Path) {
    let mut names = Vec::new();
    if std::env::var_os("CARGO_FEATURE_PREVIEW").is_some() {
        if let Ok(dir) = std::fs::read_dir("scenes") {
            for e in dir.flatten() {
                let p = e.path();
                if p.extension().is_some_and(|x| x == "json") {
                    if let Some(stem) = p.file_stem().and_then(|s| s.to_str()) {
                        names.push(stem.to_string());
                    }
                }
            }
        }
    }
    names.sort();
    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR").replace('\\', "/");
    let mut text = String::from(
        "// Generated by build.rs from scenes/*.json. Do not edit.\n\npub const SCENES: &[(&str, &str)] = &[\n",
    );
    for n in &names {
        text.push_str(&format!("    ({n:?}, include_str!({:?})),\n", format!("{dir}/scenes/{n}.json")));
    }
    text.push_str("];\n");
    if let Err(e) = std::fs::write(file, text) {
        panic!("{}: {e}", file.display())
    }
}
