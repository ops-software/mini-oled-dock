/// One language's catalogues, built the way the dock builds them.
struct World {
    apps: Arena,
    settings: Arena,
    opts: LauncherOpts,
    learned: Frecency,
    num: NumberStyle,
}

impl World {
    fn new(italian: bool) -> World {
        let mut index = AppIndex { default_rank: 12_813, ..AppIndex::default() };
        index.ranks.insert(CLASSIC_NOTEPAD.to_lowercase(), 3_114);
        let mut list = Vec::new();
        for (en, it, id, syn, rank) in APPS {
            let name = if italian { *it } else { Some(*en) };
            let Some(name) = name else { continue };
            list.push(StartApp { id: (*id).to_string(), name: name.to_string() });
            if !syn.is_empty() {
                index.synonyms.insert(name.to_lowercase(), Keys::from(*syn));
            }
            if let Some(r) = rank {
                index.ranks.insert(id.to_lowercase(), *r);
            }
        }
        let apps = catalog::build_apps(&list, Some(&index)).unwrap();
        let rows = if italian { SETTINGS_IT } else { SETTINGS_EN };
        let held: Vec<Setting> = rows
            .iter()
            .map(|(name, syn, xml, rank)| {
                let mut keys = Keys::from(*syn);
                for w in *xml {
                    keys.push(w, crate::start_search::XML_KEYWORD_PENALTY);
                }
                Setting {
                    name: (*name).into(),
                    lower: name.to_lowercase(),
                    keys: keys.tidy(),
                    rank: *rank,
                    target: Cow::Borrowed("ms-settings:"),
                    args: None,
                }
            })
            .collect();
        let settings = catalog::build_settings_arena(catalog::IN_PROCESS_KEY, &held).unwrap();
        // One invented alias (plan L2-A2): "gh" typed whole.
        let mut opts = LauncherOpts::default();
        let aliases = [("gh".to_string(), "https://example.com/gh".to_string())].into_iter().collect();
        opts.aliases = super::aliases::AliasTable::build(&aliases, &opts.prefixes).0;
        World { apps, settings, opts, learned: Frecency::new(), num: if italian { IT_NUM } else { EN_NUM } }
    }

    fn cx(&self) -> Context<'_> {
        Context {
            apps: self.apps.view(),
            settings: self.settings.view(),
            windows: &[],
            history: &[],
            opts: &self.opts,
            num: self.num,
            now_unix: 1_790_000_000,
            utc_offset_min: 0,
            time_style: Default::default(),
            learned: &self.learned,
            window_target: true,
        }
    }
}

/// What one query shows: the rows in view order, the selection, the mode.
struct Shown {
    rows: Vec<Item>,
    sel: Option<usize>,
    mixed: bool,
    text: String,
}

impl Shown {
    fn of(w: &World, raw: &str) -> Shown {
        let q = query::parse_query(raw, &w.opts.prefixes, w.num, 1);
        let top = providers::query_all(&q, &w.cx(), &mut Budget::default());
        let mut res = Results::default();
        res.sync(&q, top, usize::from(w.opts.rows));
        Shown {
            rows: res.rows().to_vec(),
            sel: res.selected_index(),
            mixed: q.mode == super::model::Mode::Mixed,
            text: q.text.trim().to_string(),
        }
    }

    fn visible(&self, w: &World) -> &[Item] {
        &self.rows[..self.rows.len().min(usize::from(w.opts.rows))]
    }

    fn has_web(&self) -> bool {
        self.rows.iter().any(|r| r.key == web_search_key())
    }
}

/// The checks of one row of the table (Appendix B.2); a failure is a line of text.
fn check(w: &World, ui: &str, raw: &str, first: &str, sel: &str, checks: &str) -> Vec<String> {
    let s = Shown::of(w, raw);
    let mut bad = Vec::new();
    let mut fail = |what: String| bad.push(format!("{ui}|{raw}: {what}"));
    let top = s.rows.first();
    let title = top.map_or("(no rows)", |r| &*r.title);
    match first {
        "-" => {}
        "web" => {
            if top.map(|r| r.key) != Some(web_search_key()) {
                fail(format!("first row is {title:?}, wanted the web row"));
            }
        }
        "path" => {
            if !top.is_some_and(|r| matches!(r.kind, Kind::File | Kind::Folder)) {
                fail(format!("first row is {title:?}, wanted the path row"));
            }
        }
        f if f.starts_with("run ") => {
            if !top.is_some_and(|r| r.kind == Kind::RunLine && *r.title == f[4..]) {
                fail(format!("first row is {title:?}, wanted the run row {:?}", &f[4..]));
            }
        }
        f if f.starts_with("answer ") => {
            if !top.is_some_and(|r| r.kind == Kind::Answer && *r.title == f[7..]) {
                fail(format!("first row is {title:?}, wanted the answer {:?}", &f[7..]));
            }
        }
        f => {
            if title != f {
                let list: Vec<&str> = s.rows.iter().take(4).map(|r| &*r.title).collect();
                fail(format!("first row is {title:?}, wanted {f:?} (rows: {list:?})"));
            }
        }
    }
    match (sel, s.sel) {
        ("y", Some(0)) | ("n", None) | ("-", _) => {}
        ("n", Some(i)) if i != 0 => {}
        (want, got) => fail(format!("selection {got:?}, wanted {want:?}")),
    }
    let vis = s.visible(w);
    for c in split_checks(checks) {
        let c = c.as_str();
        let ok = match c {
            "W" => vis.iter().any(|r| r.key == web_search_key()),
            "R" => vis.iter().any(|r| r.kind == Kind::RunLine),
            "F0" => s.rows.iter().all(|r| r.score.tier != TIER_FUZZY),
            "S0" => s.rows.iter().all(|r| r.from != ProviderId::Settings),
            "A0" => s.rows.iter().all(|r| r.from != ProviderId::Alias),
            "alone" => s.rows.len() == 1 && s.has_web(),
            c if c.starts_with("2:") => s.rows.get(1).is_some_and(|r| *r.title == c[2..]),
            c if c.starts_with("8:") => {
                let at = vis.iter().position(|r| *r.title == c[2..]);
                at.is_some_and(|i| s.sel != Some(i))
            }
            other => {
                fail(format!("unknown check {other:?}"));
                true
            }
        };
        if !ok {
            let list: Vec<&str> = s.rows.iter().map(|r| &*r.title).collect();
            fail(format!("check {c} failed (rows: {list:?})"));
        }
    }
    bad
}

/// The checks of a row: the plain ones are single words; "2:" and "8:" take a title, which may hold spaces, up to the
/// next plain check or "2:" / "8:".
fn split_checks(checks: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for word in checks.split_whitespace() {
        let starts = matches!(word, "W" | "R" | "F0" | "S0" | "A0" | "alone")
            || word.starts_with("2:")
            || word.starts_with("8:");
        match out.last_mut() {
            Some(last) if !starts => {
                last.push(' ');
                last.push_str(word);
            }
            _ => out.push(word.to_string()),
        }
    }
    out
}

/// B.3, over one row's results.
fn invariants_of(w: &World, ui: &str, raw: &str) -> Vec<String> {
    let s = Shown::of(w, raw);
    let mut bad = Vec::new();
    let mut fail = |what: &str| bad.push(format!("{ui}|{raw}: {what}"));
    let folded = {
        let mut f = String::new();
        rank::fold(&s.text, &mut f);
        f
    };
    // 1. A selected destructive command is one the query names.
    if let Some(r) = s.sel.and_then(|i| s.rows.get(i)) {
        if r.destructive {
            let ok = matches!(&r.payload, super::model::Payload::Command(id)
                if rank::name_allows_default(&folded, keywords::destructive_names(*id)));
            if !ok {
                fail("a destructive command is selected by a query that does not name it");
            }
        }
    }
    let vis = s.visible(w);
    // 2. The web row is visible; in Mixed mode from 3 characters, unless the line is a calculation.
    let answer = s.rows.iter().any(|r| r.kind == Kind::Answer);
    if s.has_web() && !vis.iter().any(|r| r.key == web_search_key()) {
        fail("the web row is below the visible rows");
    }
    if s.mixed && folded.chars().count() >= 3 && !answer && !s.has_web() {
        fail("no web row from 3 characters in Mixed mode");
    }
    // 3. A known command's first word: the run row is visible.
    let known = query::implicit(&s.text, &|w| runline::known_for(w).is_some()) == Some(Implicit::Command);
    if s.mixed && known && !vis.iter().any(|r| r.kind == Kind::RunLine) {
        fail("the run row is not visible for a known command");
    }
    // 4. Mixed mode: at most 3 settings rows that only a hidden word matched.
    if s.mixed {
        let hidden =
            s.rows.iter().filter(|r| r.from == ProviderId::Settings && HIDDEN_TIERS.contains(&r.score.tier)).count();
        if hidden > 3 {
            fail(&format!("{hidden} hidden-only settings rows"));
        }
    }
    // 5. No fuzzy row beside a run, path, URL, answer or registry row.
    let answered = s.rows.iter().any(|r| {
        matches!(r.kind, Kind::RunLine | Kind::File | Kind::Folder | Kind::Answer)
            || (r.from == ProviderId::Web && r.key != web_search_key())
            || (r.from == ProviderId::Registry && !s.mixed)
    });
    if answered && s.rows.iter().any(|r| r.score.tier == TIER_FUZZY) {
        fail("a fuzzy row beside an answer, run, path, URL or registry row");
    }
    // 6. An alias row only for a Mixed query equal to its word, first and selected (plan L2 D9).
    for (i, r) in s.rows.iter().enumerate().filter(|(_, r)| r.from == ProviderId::Alias) {
        let mut word = String::new();
        rank::fold(&r.title, &mut word);
        if !s.mixed || word != folded || i != 0 || s.sel != Some(0) {
            fail("an alias row out of place");
        }
    }
    bad
}

