#requires -Version 7
<#
.SYNOPSIS
  Regenerates the Rust-crate part of THIRD_PARTY_NOTICES.md.
.DESCRIPTION
  Everything above the marker line "<!-- below: generated by tools/gen-notices.ps1 -->" is hand-written
  and kept. Everything after it is rebuilt from `cargo tree` (the crates in dock.exe) and
  `cargo metadata` (where each crate's licence files live). Installs nothing.
  Exits 1, naming the crate, for a licence expression outside the accepted list or a crate without
  a licence file: accepting a new licence is a decision for the owner.
#>
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$notices = Join-Path $root 'THIRD_PARTY_NOTICES.md'
$marker = '<!-- below: generated by tools/gen-notices.ps1 -->'
$accepted = @(
  'MIT',
  'MIT OR Apache-2.0',
  '(MIT OR Apache-2.0) AND Unicode-3.0',
  'Unlicense OR MIT'
)

Push-Location $root
try {
  $tree = & cargo tree --locked --offline -e normal --target x86_64-pc-windows-msvc --prefix none -f '{p}|{l}'
  if ($LASTEXITCODE -ne 0) { throw 'cargo tree failed' }
  $metaJson = & cargo metadata --locked --offline --format-version 1
  if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }
  $meta = ($metaJson | Out-String) | ConvertFrom-Json
} finally { Pop-Location }

# name -> version -> licence expression, root (first line) skipped.
$crates = [ordered]@{}
$first = $true
foreach ($line in $tree) {
  if ($first) { $first = $false; continue }
  $pkg, $lic = $line -split '\|', 2
  $lic = ($lic -replace ' \(\*\)$', '').Trim()
  $pkg = ($pkg -replace ' \(\*\)$', '' -replace ' \(proc-macro\)$', '').Trim()
  if ($pkg -notmatch '^(?<n>\S+) v(?<v>\S+)$') { throw "unexpected cargo tree line: $line" }
  $key = "$($Matches.n) $($Matches.v)"
  if ($crates.Contains($key)) { continue }
  if ($accepted -notcontains $lic) {
    Write-Error "crate $key has licence '$lic', which is not in the accepted list; ask the owner"
    exit 1
  }
  $crates[$key] = [pscustomobject]@{ Name = $Matches.n; Version = $Matches.v }
}

# Licence text -> crates using it. Ordinal keys: texts that differ only in letter case stay apart.
$groups = [System.Collections.Generic.Dictionary[string, System.Collections.Generic.List[string]]]::new([System.StringComparer]::Ordinal)
foreach ($key in $crates.Keys) {
  $c = $crates[$key]
  $pkg = @($meta.packages | Where-Object { $_.name -eq $c.Name -and $_.version -eq $c.Version })
  if ($pkg.Count -ne 1) { Write-Error "crate $key not found in cargo metadata"; exit 1 }
  $dir = Split-Path -Parent $pkg[0].manifest_path
  $files = @(Get-ChildItem -LiteralPath $dir -File | Where-Object {
      $_.Name -match '^(LICENSE|COPYING)' -and $_.Name -notmatch '^UNLICENSE'
    } | Sort-Object Name)
  if ($files.Count -eq 0) { Write-Error "crate $key has no LICENSE* or COPYING* file"; exit 1 }
  foreach ($f in $files) {
    $text = [System.IO.File]::ReadAllText($f.FullName, [System.Text.UTF8Encoding]::new($false))
    $text = ($text -replace "`r`n", "`n" -replace "`r", "`n").TrimEnd("`n", ' ', "`t")
    if ($text.Contains('```')) { Write-Error "licence text of $key contains a code fence"; exit 1 }
    if (-not $groups.ContainsKey($text)) { $groups[$text] = [System.Collections.Generic.List[string]]::new() }
    if (-not $groups[$text].Contains($key)) { $groups[$text].Add($key) }
  }
}

$head = [System.IO.File]::ReadAllText($notices, [System.Text.UTF8Encoding]::new($false)) -replace "`r`n", "`n"
$at = $head.IndexOf($marker)
if ($at -lt 0) { Write-Error "marker line not found in THIRD_PARTY_NOTICES.md"; exit 1 }
$head = $head.Substring(0, $at + $marker.Length)

$fence = '```'
$sb = [System.Text.StringBuilder]::new()
[void]$sb.Append($head).Append("`n`n")
[void]$sb.Append("## Rust crates used to build dock.exe`n`n")
[void]$sb.Append("Every normal dependency of dock.exe, compile-time macro crates included. Licence texts are copied from each crate's package.`n")

# Stable order: by the first crate name of each group.
$ordered = $groups.GetEnumerator() | Sort-Object { ($_.Value | Sort-Object)[0] }, { $_.Key }
$n = 0
foreach ($g in $ordered) {
  $n++
  $used = ($g.Value | Sort-Object) -join ', '
  [void]$sb.Append("`n### Licence text $n`n`nUsed by: $used`n`n$fence`n$($g.Key)`n$fence`n")
}
[System.IO.File]::WriteAllText($notices, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Host "wrote ${notices}: $($crates.Count) crates, $n licence texts"
