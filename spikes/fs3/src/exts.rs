#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn l1_holds_300_distinct_plain_extensions() {
        let mut v: Vec<&str> = L1.to_vec();
        v.sort_unstable();
        v.dedup();
        assert_eq!(v.len(), 300, "duplicates in L1");
        for e in L1 {
            assert!(
                !e.is_empty() && e.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-'),
                "{e}"
            );
        }
    }
}
